import { InvestigatorStatic, PossessionCard } from '../types';
import { PRESET_POSSESSIONS } from './possessionsCatalog';

function getPossession(id: string): PossessionCard {
  const item = PRESET_POSSESSIONS.find((p) => p.id === id);
  if (!item) {
    console.warn('Possession card ID not found: ' + id);
    return {
      id,
      name: id,
      type: 'item',
      effectText: 'Starting item.',
    };
  }
  return item;
}


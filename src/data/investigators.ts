import { InvestigatorStatic, PossessionCard } from '../types';
import { PRESET_POSSESSIONS } from './possessionsCatalog';

export function getPossession(id: string): PossessionCard {
  const cleanId = id.trim();
  const lowerClean = cleanId.toLowerCase();
  const slug = lowerClean.replace(/\s+/g, '-');

  // 1. Exact or slug ID match
  let item = PRESET_POSSESSIONS.find((p) => p.id === cleanId || p.id === slug);
  if (item) return item;

  // 2. Spell prefix check (e.g. 'arcane-insight' -> 'spell-arcane-insight')
  if (!slug.startsWith('spell-')) {
    item = PRESET_POSSESSIONS.find((p) => p.id === `spell-${slug}`);
    if (item) return item;
  } else {
    const withoutPrefix = slug.replace(/^spell-/, '');
    item = PRESET_POSSESSIONS.find((p) => p.id === withoutPrefix);
    if (item) return item;
  }

  // 3. Condition prefix check
  if (!slug.startsWith('condition-')) {
    item = PRESET_POSSESSIONS.find((p) => p.id === `condition-${slug}`);
    if (item) return item;
  }

  // 4. Exact card name match (case-insensitive)
  item = PRESET_POSSESSIONS.find((p) => p.name.toLowerCase() === lowerClean);
  if (item) return item;

  console.warn('Possession card ID not found: ' + id);
  return {
    id,
    name: id,
    type: 'item',
    effectText: 'Starting item.',
  };
}

